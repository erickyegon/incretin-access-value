"""Writes docs/data_dictionary_marts.md: every column of every mart (name, type, unit, description) from the live warehouse schema and the dbt column descriptions (dbt/models/marts/schema.yml).
Units are inferred from column-name patterns and listed in the legend; where no pattern applies the unit is blank. Run: python scripts/build/gen_data_dictionary_marts.py"""
import pathlib, re, subprocess, yaml, csv, io
root = pathlib.Path(__file__).resolve().parents[2]
PSQL = r"C:\Program Files\PostgreSQL\17\bin\psql.exe"
out = subprocess.run([PSQL, "-U", "postgres", "-h", "localhost", "-d", "incretin", "-At", "-F", "|", "-c",
                      "select table_name, column_name, data_type from information_schema.columns where table_schema='marts' order by table_name, ordinal_position"], capture_output=True, text=True, encoding="utf-8").stdout
cols = {}
for line in out.strip().split("\n"):
    t, c, ty = line.split("|"); cols.setdefault(t, []).append((c, ty))
sch = yaml.safe_load(open(root / "dbt" / "models" / "marts" / "schema.yml", encoding="utf-8"))
desc = {m["name"]: (m.get("description") or "", {c["name"]: (c.get("description") or "") for c in m.get("columns", [])}) for m in sch["models"]}
UNITS = [(r"per_1000", "prescriptions per 1,000 enrollees in the quarter"), (r"^rx_.*upper_bound", "prescriptions; unsuppressed plus up to 10 for each suppressed cell"), (r"^rx_|prescriptions", "prescriptions (observed = unsuppressed rows only)"),
         (r"amount|spending|reimburs|payment|dollars", "US dollars (Medicaid and Part D amounts are gross of rebates)"), (r"^enrollment_", "persons (average of monthly counts in the quarter)"), (r"claims|beneficiar|n_rows|n_suppressed|n_months|n_ndcs", "count"),
         (r"share|_pct|_pc$", "proportion or percent as named"), (r"nppes|npi$|npi_", "identifier (not published)"), (r"^year$|_year$", "calendar year"), (r"quarter", "calendar quarter"), (r"weight|wt", "survey weight"), (r"wtmec|wtph|sdmv", "NHANES survey design variable")]
def unit(c):
    for p, u in UNITS:
        if re.search(p, c): return u
    return ""
MD = ["# Data dictionary: marts (generated)", "", "Generated by `scripts/build/gen_data_dictionary_marts.py` from the warehouse schema and `dbt/models/marts/schema.yml`. The conventions that apply to every mart are in [data_dictionary.md](data_dictionary.md):",
      "NDC is the drug code (no HCPCS J-codes), SDUD counts under 11 are suppressed, and amounts are gross of rebates.", ""]
for t in sorted(cols):
    md, cd = desc.get(t, ("", {}))
    MD += [f"## {t}", "", md, "", "| column | type | unit | description |", "|---|---|---|---|"]
    for c, ty in cols[t]:
        MD.append(f"| {c} | {ty} | {unit(c)} | {cd.get(c, '').replace('|', '/')} |")
    MD.append("")
(root / "docs" / "data_dictionary_marts.md").write_text("\n".join(MD), encoding="utf-8")
print(len(cols), "marts,", sum(len(v) for v in cols.values()), "columns")
