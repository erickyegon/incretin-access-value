"""Generate dbt files that mirror the raw schema: models/staging/_sources.yml and the NHANES / MEPS staging models.
These sources have many columns (MEPS FYC 2024 has 1,615), so the SQL is generated from information_schema instead of typed by hand.
Column names are lower-cased (snake case already for NHANES/MEPS codes); values keep the raw type. Re-run after reloading raw tables.
Connection: local PostgreSQL, database incretin (trust authentication on localhost)."""
import re
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parents[2]
STG = ROOT / "dbt" / "models" / "staging"
con = psycopg2.connect(host="localhost", dbname="incretin", user="postgres")
cur = con.cursor()
cur.execute("""select table_name, column_name, data_type from information_schema.columns
               where table_schema='raw' and column_name not in ('_source_file','_loaded_at','_sha256','_load_log')
               order by table_name, ordinal_position""")
cols = {}
for t, c, d in cur.fetchall():
    cols.setdefault(t, []).append((c, d))
cur.execute("select table_name from information_schema.tables where table_schema='raw' and table_name not like '\\_%' order by 1")
tables = [r[0] for r in cur.fetchall()]

# ---- sources ------------------------------------------------------------------------------------------------------------
lines = ["version: 2", "", "sources:", "  - name: raw", "    description: \"Interim Parquet files loaded unchanged into PostgreSQL by scripts/load/load_raw.py (original column names; _source_file, _loaded_at, _sha256 metadata added).\"", "    schema: raw", "    tables:"]
for t in tables:
    lines += [f"      - name: {t}", f"        description: \"Raw load of {t} (see docs/load_reconciliation.csv for source file and checks).\""]
(STG / "_sources.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def sel(table, extra=""):
    return ",\n    ".join(f'"{c}" as {c.lower()}' if c != c.lower() else c for c, _ in cols[table])


def rename(c):
    return re.sub(r"\W+", "_", c.lower()).strip("_")


# ---- NHANES: one model per component, two cycles stacked (columns outer-joined; absent in a cycle = NULL) ---------------------------
NH = {"demo": ("nhanes_demo_l", "nhanes_p_demo"), "bmx": ("nhanes_bmx_l", "nhanes_p_bmx"), "bpxo": ("nhanes_bpxo_l", "nhanes_p_bpxo"),
      "bpq": ("nhanes_bpq_l", "nhanes_p_bpq"), "ghb": ("nhanes_ghb_l", "nhanes_p_ghb"), "diq": ("nhanes_diq_l", "nhanes_p_diq"),
      "mcq": ("nhanes_mcq_l", "nhanes_p_mcq"), "rxq_rx": ("nhanes_rxq_rx_l", "nhanes_p_rxq_rx")}
CYC = ("2021_2023", "2017_2020")
for comp, (a, b) in NH.items():
    allcols = []
    types = {}
    for t in (a, b):
        for c, d in cols[t]:
            if c.lower() not in types:
                types[c.lower()] = d
                allcols.append(c.lower())
    parts = []
    for t, cyc in zip((a, b), CYC):
        have = {c.lower() for c, _ in cols[t]}
        sc = []
        for c in allcols:
            if c in have:
                real = next(x for x, _ in cols[t] if x.lower() == c)
                sc.append(f'"{real}" as {c}' if real != c else c)
            else:
                sc.append(f"null::{'double precision' if types[c] == 'double precision' else 'text'} as {c}")
        parts.append(f"select\n    '{cyc}' as cycle,\n    " + ",\n    ".join(sc) + f"\nfrom {{{{ source('raw', '{t}') }}}}")
    (STG / f"stg_nhanes__{comp}.sql").write_text("-- generated by scripts/build/gen_dbt_wide_models.py\n" + "\nunion all\n".join(parts) + "\n", encoding="utf-8")
(STG / "stg_nhanes__rxq_drug.sql").write_text(
    "-- generated by scripts/build/gen_dbt_wide_models.py (RXQ_DRUG drug-code lookup, 1988-2020; no cycle column)\nselect\n    " + sel("nhanes_rxq_drug") + "\nfrom {{ source('raw', 'nhanes_rxq_drug') }}\n", encoding="utf-8")

# ---- MEPS ---------------------------------------------------------------------------------------------------------------------------
for t in ("meps_cond_2023", "meps_cond_2024", "meps_rx_2023", "meps_rx_2024", "meps_fyc_2023"):
    (STG / f"stg_{t.replace('meps_', 'meps__')}.sql").write_text(
        "-- generated by scripts/build/gen_dbt_wide_models.py\nselect\n    " + sel(t) + f"\nfrom {{{{ source('raw', '{t}') }}}}\n", encoding="utf-8")
p1 = [c for c, _ in cols["meps_fyc_2024_p1"]]
p2 = [c for c, _ in cols["meps_fyc_2024_p2"] if c.lower() != "dupersid"]
# PostgreSQL relations (tables AND views) hold at most 1,600 columns; the 2024 FYC file has 1,615. Drop columns whose values are
# identical, for all persons, to an earlier column of the file (first occurrence kept): no information is lost for this release.
hashes = {}
for t, cs in (("meps_fyc_2024_p1", p1), ("meps_fyc_2024_p2", p2)):
    for i in range(0, len(cs), 100):
        ch = cs[i:i + 100]
        cur.execute("select " + ",".join(f"md5(string_agg(coalesce(\"{c}\"::text,'~'),',' order by \"DUPERSID\"))" for c in ch) + f" from raw.{t}")
        for c, v in zip(ch, cur.fetchone()):
            hashes[c] = v
seen, dropped = {}, []
for c in p1 + p2:
    if hashes[c] in seen:
        dropped.append((c, seen[hashes[c]]))
    else:
        seen[hashes[c]] = c
dropset = {c for c, _ in dropped}
p1k = [c for c in p1 if c not in dropset]
p2k = [c for c in p2 if c not in dropset]
assert len(p1k) + len(p2k) <= 1600, "still over the PostgreSQL column limit"
body = ",\n    ".join([f'p1."{c}" as {c.lower()}' for c in p1k] + [f'p2."{c}" as {c.lower()}' for c in p2k])
dropnote = "; ".join(f"{c} (= {k})" for c, k in dropped)
header = (
    "-- generated by scripts/build/gen_dbt_wide_models.py\n"
    "-- The 2024 Full Year Consolidated file has 1,615 variables. PostgreSQL tables and views hold at most 1,600 columns, so the loader split\n"
    "-- the file into raw.meps_fyc_2024_p1 and _p2 keyed on DUPERSID, and this view re-joins them one-to-one (tested: equal row counts,\n"
    "-- no person missing from either part). To fit the limit, " + str(len(dropped)) + " columns whose values are identical for all persons to an earlier\n"
    "-- column are not exposed (dropped (= kept twin)): " + dropnote + ".\n"
)
sql = (header + "select\n    " + body + "\nfrom {{ source('raw', 'meps_fyc_2024_p1') }} p1\n"
       "inner join {{ source('raw', 'meps_fyc_2024_p2') }} p2 on p1.\"DUPERSID\" = p2.\"DUPERSID\"\n")
(STG / "stg_meps__fyc_2024.sql").write_text(sql, encoding="utf-8")
print("meps fyc 2024 columns exposed:", len(p1k) + len(p2k), "dropped:", len(dropped))
print("sources:", len(tables), "tables;", "nhanes models:", len(NH) + 1, "meps models: 6")
